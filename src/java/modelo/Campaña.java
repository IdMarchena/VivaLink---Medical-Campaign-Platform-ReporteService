package modelo;

/**
 *
 * @author Usuario
 */
public class Campaña {
    private int id;
    private String nombre;

    @Override
    public String toString() {
        return "Campa\u00f1a{" + "id=" + id + ", nombre=" + nombre + '}';
    }

    public Campaña(int id, String nombre) {
        this.id = id;
        this.nombre = nombre;
    }

    /**
     * @return the id
     */
    public int getId() {
        return id;
    }

    /**
     * @param id the id to set
     */
    public void setId(int id) {
        this.id = id;
    }

    /**
     * @return the nombre
     */
    public String getNombre() {
        return nombre;
    }

    /**
     * @param nombre the nombre to set
     */
    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}
